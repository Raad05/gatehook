export type JurisdictionCode = Exclude<(typeof JURISDICTIONS)[number], ''>;

const INDEX_BY_CODE = new Map<string, number>(JURISDICTIONS.map((code, i) => [code, i]));

/** On-chain index for an ISO 3166-1 alpha-2 code. Throws on unknown codes. */
export function jurisdictionIndex(code: string): number {
  const index = code ? INDEX_BY_CODE.get(code.toUpperCase()) : undefined;
  if (index === undefined) throw new Error(`Unknown jurisdiction code: ${code}`);
  return index;
}

/** ISO code for an on-chain index, or `undefined` for unset/unknown. */
export function jurisdictionCode(index: number): JurisdictionCode | undefined {
  const code = JURISDICTIONS[index];
  return code ? code : undefined;
}

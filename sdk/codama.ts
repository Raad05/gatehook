// Regenerates src/generated from the Anchor IDL. Run after `anchor build`.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { rootNodeFromAnchor, type AnchorIdl } from '@codama/nodes-from-anchor';
import { renderVisitor } from '@codama/renderers-js';
import { createFromRoot } from 'codama';

const idlPath = fileURLToPath(new URL('../target/idl/gatehook.json', import.meta.url));
const idl = JSON.parse(readFileSync(idlPath, 'utf8')) as AnchorIdl;
const codama = createFromRoot(rootNodeFromAnchor(idl));

await codama.accept(
  renderVisitor(fileURLToPath(new URL('.', import.meta.url)), {
    generatedFolder: 'src/generated',
    deleteFolderBeforeRendering: true,
    syncPackageJson: false,
    importExtension: 'ts',
  }),
);

// Codama's getGatehookErrorMessage returns a placeholder when NODE_ENV=production
// (every bundled frontend). Compliance rejections are user-facing, so also emit an
// always-available message table straight from the IDL.
const errors = (idl as unknown as { errors?: { code: number; name: string; msg?: string }[] }).errors ?? [];
writeFileSync(
  fileURLToPath(new URL('./src/generated/errorMessages.ts', import.meta.url)),
  [
    '// Generated by codama.ts from the Anchor IDL. Do not edit.',
    '',
    '/** Error messages by code, available in production bundles too. */',
    'export const GATEHOOK_ERROR_MESSAGES: Readonly<Record<number, string>> = {',
    ...errors.map((e) => `  ${e.code}: ${JSON.stringify(e.msg ?? e.name)},`),
    '};',
    '',
  ].join('\n'),
);
